def build_catalog(monsters, population, regions):
    """Serialize base stats and deduplicated habitats from authoritative definitions."""
    catalog = []
    for kind, spec in monsters.items():
        lore, tactics, loot = FIELD_NOTES.get(kind, (
            "Новый обитатель земель Эха.",
            ["Следи за отметкой атаки и выходи из неё до завершения замаха."],
            ["Опыт и монеты за участие в победе."]))
        habitats = [{"id": rid, "name": regions[rid]["name"], "level": regions[rid]["level"]}
                    for rid, rows in population.items() if rid in regions
                    and any(row[0] == kind and row[1] > 0 for row in rows)]
        catalog.append({
            "id": kind, "name": spec["name"], "regions": habitats,
            "boss": is_boss_kind(kind, spec), "mini_boss": bool(spec.get("mini_boss")),
            "color": spec["color"], "size": spec["size"],
            "base_hp": spec["hp"], "base_damage": spec["damage"],
            "range": spec["range"], "cooldown": spec["cooldown"], "xp": spec["xp"],
            "lore": lore, "tactics": list(tactics), "loot": list(loot),
        })
    return catalog
