"""Bestiary display copy and bounded collection history, independent of the server."""
import math
import re


MAX_BESTIARY_KILLS = 1_000_000


def is_boss_kind(kind, spec):
    # The original colossus predates the explicit boss flag in MONSTERS.
    return bool(spec.get("boss") or kind == "colossus")


def sanitize_kills(raw, monsters, bosses_defeated=None):
    """Keep known species and integral counts; recover only recorded boss history."""
    result = {}
    if isinstance(raw, dict):
        for kind, value in raw.items():
            if kind not in monsters or isinstance(value, bool):
                continue
            if isinstance(value, str):
                if not re.fullmatch(r"[+-]?[0-9]+", value.strip()):
                    continue
            elif not isinstance(value, (int, float)):
                continue
            if isinstance(value, float) and (not math.isfinite(value) or not value.is_integer()):
                continue
            try:
                result[kind] = max(0, min(MAX_BESTIARY_KILLS, int(value)))
            except (ValueError, OverflowError):
                continue
    if isinstance(bosses_defeated, list):
        for kind in bosses_defeated:
            if isinstance(kind, str) and kind in monsters and is_boss_kind(kind, monsters[kind]):
                result[kind] = max(1, result.get(kind, 0))
    return result


